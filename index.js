import 'dotenv/config';
import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import { rateLimit } from 'express-rate-limit';
import fs from 'node:fs';
import path from 'node:path';
import connectDB from './src/DB/connection.js';
import authRouter from './src/modules/auth/auth.router.js';
import userRouter from './src/modules/user/user.router.js';
import messageRouter from './src/modules/message/message.router.js';
import { notFound, errorHandler } from './src/middleware/errorHandler.js';
const required=['MONGO_URI','JWT_ACCESS_SECRET','JWT_REFRESH_SECRET','PHONE_ENCRYPTION_KEY'];
for(const name of required)if(!process.env[name])throw new Error(`Missing required environment variable: ${name}`);
const app=express();
app.disable('x-powered-by');app.use(helmet());app.use(cors({origin:process.env.CLIENT_ORIGIN||'*'}));app.use(express.json({limit:'20kb'}));app.use('/uploads',express.static(path.resolve('uploads')));
app.use(rateLimit({windowMs:15*60*1000,limit:200,standardHeaders:true,legacyHeaders:false}));
app.use('/api/auth',authRouter);app.use('/api/users',userRouter);app.use('/api/messages',messageRouter);
app.get('/health',(req,res)=>res.json({status:'success',message:'Saraha API is running'}));app.use(notFound);app.use(errorHandler);
const port=Number(process.env.PORT||3000);
connectDB().then(()=>app.listen(port,()=>console.log(`Saraha API listening on port ${port}`))).catch((err)=>{console.error('Could not connect to MongoDB:',err.message);process.exit(1);});
